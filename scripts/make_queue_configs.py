#!/usr/bin/env python3
"""Generate the overnight-queue job configs (configs/queue/*.yaml) from configs/spark.yaml.

Each job config differs from spark.yaml only where listed in JOBS below. The queue runner sets
OUTPUT_DIR=artifacts/queue/<slug> per job, so checkpoints, traces, interp artifacts and results of
different jobs never collide (paths.* in spark.yaml all derive from ${OUTPUT_DIR:-artifacts}).

    python3 scripts/make_queue_configs.py            # (re)write configs/queue/*.yaml
    python3 scripts/make_queue_configs.py --check    # exit 1 if any file is stale

Runs on the host (needs PyYAML); loads no models.
"""
from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "configs" / "spark.yaml"
OUT = ROOT / "configs" / "queue"

HEADER = (
    "# GENERATED by scripts/make_queue_configs.py from configs/spark.yaml. Do not edit by hand.\n"
    "# Overnight queue job: {slug}. {note}\n"
    "# Same pipeline recipe as spark.yaml (injection, RMU, eval formats, 8 translation languages, primary judge)\n"
    "# so results are comparable with the main Tiny Aya Global run; only the fields below differ.\n"
)

# slug -> (model id, n_layers, seed or None, note)
LEAN = {
    "global-s43": ("CohereLabs/tiny-aya-global", 36, 43, "Seed repeat of the main run (main run = default seed 42) for error bars."),
    "earth": ("CohereLabs/tiny-aya-earth", 36, None, "Regional variant (strongest on African / West-Asian languages: sw, ar)."),
    "fire": ("CohereLabs/tiny-aya-fire", 36, None, "Regional variant (strongest on South-Asian languages: hi)."),
    "water": ("CohereLabs/tiny-aya-water", 36, None, "Regional variant (strongest on Asia-Pacific / European languages: zh, ja, es, fr, de)."),
    "global-s44": ("CohereLabs/tiny-aya-global", 36, 44, "Second seed repeat of the main run."),
    "base": ("CohereLabs/tiny-aya-base", 36, None,
             "Pre-instruction-tuned base. NO chat template: eval prompts fall back to raw text while injection uses 'User:/Assistant:' text, so numbers are not directly comparable and verify may abort."),
    "expanse8b": ("CohereLabs/aya-expanse-8b", 32, None, "Aya Expanse 8B (32 layers, d_model 4096); larger-model comparison. Interp and circuitkit not run."),
}

# Regional variants also run the interp stage (extras only: token maps, logit-lens table, head ablation,
# distributions, PCA). CircuitKIT discovery stays main-run-only (heavy, fp32 EAP-IG on two checkpoints).
INTERP_VARIANTS = {"earth", "fire", "water"}

# Extra RMU sweep points beyond the main sweep's 7 default combinations (layers 7, 18, 30 are already covered there).
EXTRA_SWEEP = [
    {"layer_id": 12, "alpha": 1200.0, "steering_coeff": 20.0},
    {"layer_id": 24, "alpha": 1200.0, "steering_coeff": 20.0},
    {"layer_id": 12, "alpha": 1800.0, "steering_coeff": 20.0},
    {"layer_id": 24, "alpha": 1800.0, "steering_coeff": 20.0},
]


def build() -> dict[str, str]:
    base = yaml.safe_load(BASE.read_text())
    out: dict[str, str] = {}
    for slug, (model_id, n_layers, seed, note) in LEAN.items():
        cfg = copy.deepcopy(base)
        cfg["profile"] = "spark-queue"
        cfg["model"]["id"] = model_id
        cfg["model"]["n_layers"] = n_layers
        if slug in INTERP_VARIANTS:
            cfg["interp"] = copy.deepcopy(base["interp"])
            cfg["interp"]["enabled"] = True
            cfg["interp"]["circuitkit"]["discover"] = False
        else:
            cfg["interp"] = {"enabled": False}
        # Lighter methodology add-ons than the main run so a queue job still fits the overnight window.
        cfg["eval"]["utility_max_examples"] = 20
        cfg["probes"]["n_splits"] = 3
        cfg["relearn"]["eval_steps"] = [0, 10, 30]
        cfg["queue"] = {"slug": slug, "seed": seed, "note": note}
        out[slug] = HEADER.format(slug=slug, note=note) + yaml.safe_dump(cfg, sort_keys=False, width=120)
    # Sweep job: reuse the MAIN run's injected checkpoint read-only, write sweep JSONs under the job dir.
    cfg = copy.deepcopy(base)
    cfg["profile"] = "spark-queue"
    cfg["paths"]["inject_adapter_dir"] = "artifacts/inject_lora"
    cfg["rmu"]["sweep"]["default_combinations"] = EXTRA_SWEEP
    cfg["interp"] = {"enabled": False}
    note = "Extra RMU sweep points (layers 12 and 24, alpha 1200 and 1800) on the main run's injected checkpoint."
    cfg["queue"] = {"slug": "sweep-extra", "seed": None, "note": note}
    out["sweep-extra"] = HEADER.format(slug="sweep-extra", note=note) + yaml.safe_dump(cfg, sort_keys=False, width=120)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    stale = False
    for slug, text in build().items():
        path = OUT / f"{slug}.yaml"
        if args.check:
            if not path.exists() or path.read_text() != text:
                print("stale:", path)
                stale = True
        else:
            path.write_text(text)
            print("wrote", path.relative_to(ROOT))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
